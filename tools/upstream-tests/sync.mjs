// Run upstream's vitest suite against the fork.
//
//   node tools/upstream-tests/sync.mjs          # (re)build the run directory
//   cd <run dir> && npx vitest run              # run the suite there
//   cd <run dir> && npx vitest run --reporter=json --outputFile=out.json
//   node tools/upstream-tests/compare.mjs a.json b.json   # fixes/regressions
//
// The run directory (default: <os tmp>/vsc-uxp-upstream-tests, override with
// VSC_TEST_RUN_DIR) receives upstream's tests/{unit,integration,helpers,
// fixtures} and vitest config, a copy of the fork's src/, and a generated
// tests/helpers/module-loader.js that imports the fork's modules in the real
// injection order from overlay.js. Dependencies are never installed
// automatically; the first run prints the pinned npm command.
//
// Expect failures in tests of things the fork replaces by design: chrome.*
// storage and the content bridge, utils/blacklist.js and site-pattern.js
// (site rules resolve in chrome), real shadow roots, adoptedStyleSheets and
// upstream's inject.css file.
import fs from 'node:fs';
import path from 'node:path';
import { repoRoot, upstreamRoot, runDir, PINNED, INSTALL_HINT, overlayScripts } from './lib.mjs';

fs.mkdirSync(runDir, { recursive: true });
for (const dir of ['tests', 'src']) {
  fs.rmSync(path.join(runDir, dir), { recursive: true, force: true });
}
for (const sub of ['unit', 'integration', 'helpers', 'fixtures']) {
  fs.cpSync(path.join(upstreamRoot, 'tests', sub), path.join(runDir, 'tests', sub), {
    recursive: true,
  });
}
fs.cpSync(path.join(repoRoot, 'src'), path.join(runDir, 'src'), { recursive: true });
fs.copyFileSync(path.join(upstreamRoot, 'vitest.config.js'), path.join(runDir, 'vitest.config.js'));
fs.writeFileSync(
  path.join(runDir, 'package.json'),
  JSON.stringify(
    {
      name: 'vsc-uxp-upstream-tests',
      private: true,
      type: 'module',
      devDependencies: PINNED,
    },
    null,
    2
  ) + '\n'
);

const scripts = overlayScripts();
const core = scripts.filter((s) => s !== 'content/inject.js');
const imports = (list) => list.map((s) => `  await import('../../src/${s}');`).join('\n');
fs.writeFileSync(
  path.join(runDir, 'tests/helpers/module-loader.js'),
  `// GENERATED by tools/upstream-tests/sync.mjs from the fork's overlay.js order.
export async function loadCoreModules() {
${imports(core)}
}
export async function loadInjectModules() {
  await loadCoreModules();
  await import('../../src/content/inject.js');
}
export async function loadMinimalModules() {
${imports(['utils/key-maps.js', 'styles/controller-css-defaults.js', 'utils/constants.js', 'utils/logger.js', 'core/storage-manager.js', 'core/settings.js'])}
}
`
);

console.log(`synced ${scripts.length} fork scripts + upstream tests into ${runDir}`);
if (!fs.existsSync(path.join(runDir, 'node_modules', 'vitest', 'package.json'))) {
  console.log(`dependencies missing — install once with:\n  ${INSTALL_HINT}`);
}
